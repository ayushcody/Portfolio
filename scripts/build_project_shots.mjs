#!/usr/bin/env node
/**
 * Builds src/data/projectShots.ts from public/projects/<id>/shots.json.
 *
 * Each shots.json is an ordered list of { file, alt, caption }. The generated module adds the
 * image's pixel size (read from the JPEG/PNG header) so pages can reserve space without layout
 * shift, and it is imported statically so the data ships with every build, ISR included.
 *
 * Usage: npm run shots
 */
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const projectsDir = path.join(root, 'public', 'projects');
const outFile = path.join(root, 'src', 'data', 'projectShots.ts');

/** Width and height from a PNG IHDR chunk or a JPEG SOF marker. */
function imageSize(file) {
    const buffer = fs.readFileSync(file);
    if (buffer.readUInt32BE(0) === 0x89504e47) return { width: buffer.readUInt32BE(16), height: buffer.readUInt32BE(20) };
    if (buffer[0] === 0xff && buffer[1] === 0xd8) {
        let offset = 2;
        while (offset < buffer.length) {
            if (buffer[offset] !== 0xff) { offset += 1; continue; }
            const marker = buffer[offset + 1];
            const length = buffer.readUInt16BE(offset + 2);
            // SOF0–SOF15, except DHT (C4), JPG (C8) and DAC (CC).
            if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
                return { width: buffer.readUInt16BE(offset + 7), height: buffer.readUInt16BE(offset + 5) };
            }
            offset += 2 + length;
        }
    }
    throw new Error(`Unsupported or corrupt image: ${file}`);
}

const problems = [];
const shots = {};
const ids = fs.existsSync(projectsDir) ? fs.readdirSync(projectsDir).filter((name) => fs.existsSync(path.join(projectsDir, name, 'shots.json'))).sort() : [];

for (const id of ids) {
    const dir = path.join(projectsDir, id);
    const list = JSON.parse(fs.readFileSync(path.join(dir, 'shots.json'), 'utf8'));
    shots[id] = list.map((entry, index) => {
        const where = `${id}/shots.json[${index}]`;
        for (const key of ['file', 'alt', 'caption']) if (!entry[key]?.trim()) problems.push(`${where}: missing ${key}`);
        const file = path.join(dir, entry.file);
        if (!fs.existsSync(file)) {
            problems.push(`${where}: ${entry.file} does not exist`);
            return null;
        }
        return { src: `/projects/${id}/${entry.file}`, alt: entry.alt.trim(), caption: entry.caption.trim(), ...imageSize(file) };
    }).filter(Boolean);
}

if (problems.length) {
    console.error(problems.join('\n'));
    process.exit(1);
}

const body = `// Generated by scripts/build_project_shots.mjs from public/projects/<id>/shots.json. Do not edit by hand.

export type ProjectShot = {
    src: string;
    alt: string;
    caption: string;
    width: number;
    height: number;
};

export const projectShots: Record<string, ProjectShot[]> = ${JSON.stringify(shots, null, 4)};
`;
fs.writeFileSync(outFile, body);
console.log(`Wrote ${path.relative(root, outFile)}: ${Object.entries(shots).map(([id, list]) => `${id} (${list.length})`).join(', ') || 'no projects'}`);
